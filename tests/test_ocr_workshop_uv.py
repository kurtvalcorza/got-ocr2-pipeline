# ---- kernel <-> stage hand-off -----------------------------------------------------------------------------
def _kernel(tmp_path, shown):
    """The runtime cell's helpers, with this interpreter standing in for the isolated environment's."""
    tree = ast.parse(_src(RUNTIME_CELL))
    keep = {"show_block", "show_display", "run_stage", "read_json", "state", "belfort_split"}
    tree.body = [n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name in keep
                 or isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") in {"STAGE_SETTINGS",
                                                                                       "DISPLAY_MARKER"}]
    ns = {"json": json, "os": os, "re": re, "subprocess": subprocess, "Path": Path, "Image": Image,
          "Markdown": lambda text: ("markdown", text), "display": shown.append,
          "PYTHON": sys.executable, "STAGE_SCRIPT": STAGE_FILE, "WORK_ROOT": tmp_path / "work",
          "ENV": dict(os.environ, PYTHONIOENCODING="utf-8"), "ENVIRONMENT": {"kind": "test"}}
    exec(_src("d1171b39"), ns)
    ns.update(OUTPUT_DIR=str(tmp_path / "outputs"), WORK_DIR=str(tmp_path / "work"))
    (tmp_path / "work").mkdir()
    exec(compile(tree, RUNTIME_CELL, "exec"), ns)
    return ns


def test_run_stage_streams_output_and_renders_stage_displays(tmp_path, capsys):
    shown = []
    ns = _kernel(tmp_path, shown)
    ns["run_stage"]("pages")
    out = capsys.readouterr().out
    assert "Reference = every visible string in drawing order" in out and "notice: PUBLIC NOTICE" in out
    assert "\x1edimer-display" not in out  # display requests are rendered, not printed
    assert len(shown) == 1 and isinstance(shown[0], Image.Image) and shown[0].size == (1040, 370)
    pages = ns["state"]("pages.json")
    assert sorted(pages) == ["invoice", "notice", "report", "technical_note"]
    config = json.loads((tmp_path / "work" / "stage_config.json").read_text(encoding="utf-8"))
    assert config["ENVIRONMENT"] == {"kind": "test"} and config["WORK_DIR"] == str(tmp_path / "work")
    ns["show_display"]("\x1edimer-display " + json.dumps({"kind": "block", "title": "T", "body": "a ``` b"}))
    assert shown[-1] == ("markdown", "**T**\n\n````text\na ``` b\n````")


def test_a_failing_stage_raises_with_its_log(tmp_path, capsys):
    ns = _kernel(tmp_path, [])
    with pytest.raises(RuntimeError, match="compare failed with exit 1"):
        ns["run_stage"]("compare")  # no earlier stage has written its state
    assert "run the earlier cells of this notebook in order first" in capsys.readouterr().out


def test_belfort_split_reads_the_staged_line_images(tmp_path):
    ns = _kernel(tmp_path, [])
    state_dir = tmp_path / "work" / "state"
    state_dir.mkdir()
    split = {"splits": {"test": [{"id": "belfort-test-1", "text": "a"}]}}
    (state_dir / "belfort.json").write_text(json.dumps(split))
    line_dir = tmp_path / "work" / "belfort" / "test"
    line_dir.mkdir(parents=True)
    Image.new("RGB", (30, 10), (1, 2, 3)).save(line_dir / "belfort-test-1.png")
    [record] = ns["belfort_split"]("test")
    assert record["text"] == "a" and record["image"].getpixel((0, 0)) == (1, 2, 3)


def test_line_images_round_trip_losslessly(tmp_path, monkeypatch):
    monkeypatch.setattr(stages, "WORK_DIR", str(tmp_path / "work"))
    image = Image.fromarray(np.random.default_rng(0).integers(0, 256, (20, 50, 3), dtype=np.uint8), "RGB")
    split = {"train": [], "validation": [], "test": [{"id": "belfort-test-7", "image": image, "text": "x",
                                                      "source_row_group": 0}]}
    image_dir = stages.belfort_image_dir()
    image_dir.mkdir(parents=True)
    image.save(image_dir / "belfort-test-7.png")
    stages.save_state("belfort.json", {"image_digests": {"belfort-test-7": stages.image_digest(image)},
                                       "splits": {k: [{x: r[x] for x in ("id", "text", "source_row_group")}
                                                      for r in v] for k, v in split.items()}})
    [loaded] = stages.load_belfort_split("test", images=True)
    assert loaded["image"].tobytes() == image.tobytes()
    Image.new("RGB", (50, 20)).save(image_dir / "belfort-test-7.png")
    with pytest.raises(RuntimeError, match="differs from the verified sample"):
        stages.load_belfort_split("test", images=True)


def test_full_stage_sequence_with_model_doubles(tmp_path):
    from test_workshop_optional_paths import stage_ns

    ns = stage_ns(tmp_path)

    class Model:
        def parameters(self):
            return [types.SimpleNamespace(numel=lambda: 4)]

    def generate(*args):
        images = args[4]
        return [dict(text="PUBLIC NOTICE", doctags="<doctag><text>PUBLIC NOTICE</text></doctag>",
                     new_tokens=3, truncated=False, inference_seconds=0.1) for _ in images]

    ns.update(RUN_BELFORT=False, load_got=lambda: (Model(), None, 0, 1, 0.5),
              load_smoldoc=lambda: (Model(), None, 1, 0, 0.25), got_generate=generate, smol_generate=generate,
              RUNTIME={"device": "cpu"})
    ns["save_state"]("snapshots.json", {"got": {"dir": "g", "verify_seconds": 1.0},
                                        "smoldocling": {"dir": "s", "verify_seconds": 2.0}})
    ns["save_state"]("belfort.json", {"digest": "d", "image_digests": {}, "splits": {"test": []}})
    ns["save_state"]("baselines.json", {"empty_metrics": None, "constant_metrics": None, "constant_text": ""})
    for stage in ("pages", "got-load", "got-belfort", "got-pages", "got-probes", "smol-load", "smol-belfort",
                  "smol-pages", "smol-specialized", "smol-probes", "compare", "resources", "export", "byod",
                  "summary"):
        ns["STAGES"][stage]()
    out_root = tmp_path / "outputs"
    metrics = json.loads((out_root / "metrics.json").read_text(encoding="utf-8"))
    assert [r["parameters"] for r in metrics["resources"]] == [4, 4]
    assert len(metrics["rendered_pages"]) == 8 and len(metrics["shape_robustness"]) == 8
    provenance = json.loads((out_root / "provenance.json").read_text(encoding="utf-8"))
    assert provenance["runtime"] == {"device": "cpu"} and provenance["got"]["parameter_count"] == 4
    assert (out_root / "pages" / "notice" / "source.png").is_file()


def test_stage_command_line_rejects_unknown_stages(tmp_path):
    config = tmp_path / "config.json"
    config.write_text(json.dumps({"WORK_DIR": str(tmp_path / "work")}), encoding="utf-8")
    command = [sys.executable, str(STAGE_FILE), "--config", str(config), "--stage"]
    unknown = subprocess.run([*command, "train"], capture_output=True, text=True, timeout=60)
    assert unknown.returncode == 2 and "invalid choice" in unknown.stderr
    config.write_text(json.dumps({"WORK_DIR": "w", "EXTRA": 1}), encoding="utf-8")
    bad = subprocess.run([*command, "pages"], capture_output=True, text=True, timeout=60)
    assert bad.returncode == 1 and "unknown stage config keys: ['EXTRA']" in bad.stderr
