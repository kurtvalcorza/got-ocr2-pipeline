def test_carried_literals_are_pieces_of_at_most_1000_characters_equal_to_the_files():
    tree = ast.parse(_src("uvcarrier"))
    files = next(node.value for node in tree.body if isinstance(node, ast.Assign)
                 and node.targets[0].id == "CARRIED_FILES")
    for key, value in zip(files.keys, files.values, strict=True):
        name = ast.literal_eval(key)
        segment = ast.get_source_segment(_src("uvcarrier"), value)
        pieces = [ast.literal_eval(line.strip()) for line in segment.strip("()").splitlines() if line.strip()]
        assert pieces and all(len(piece) <= 1000 for piece in pieces), name
        assert "".join(pieces) == ast.literal_eval(value) == carrier.CARRIED[name].read_text(encoding="utf-8")


