def _notebook():
    return json.loads(NOTEBOOK.read_text(encoding="utf-8"))


def _code_cells():
    return [(c["id"], "".join(c["source"])) for c in _notebook()["cells"] if c["cell_type"] == "code"]


def _src(cid):
    return next(s for i, s in _code_cells() if i == cid)


def test_no_kernel_install_or_restart_guard():
    for cid, source in _code_cells():
        if cid == "uvcarrier":
            continue
        assert not re.search(r"-m\W+pip|^\s*[%!]\s*pip", source, re.M), cid
        for install in re.findall(r'"pip", "install"[^\n]*', source):
            assert '"--python", str(PYTHON)' in install, (cid, install)  # into the venv only
        for banned in ("Restart session", "sys.executable", "importlib.metadata", "check_call", "PINS"):
            assert banned not in source, (cid, banned)
    markdown = "\n".join("".join(c["source"]) for c in _notebook()["cells"] if c["cell_type"] == "markdown")
    assert "no restart" in markdown.lower() and "Linux x86_64 only" in markdown
    assert "Restart session" not in markdown and "restart-assisted" not in markdown


def test_kernel_imports_only_the_standard_library_and_hosted_packages():
    for cid, source in _code_cells():
        for node in ast.walk(ast.parse(source)):
            if isinstance(node, ast.Import):
                names = [a.name for a in node.names]
            elif isinstance(node, ast.ImportFrom):
                names = [node.module or ""]
            else:
                continue
            for name in names:
                assert name.split(".")[0] in KERNEL_IMPORTS, (cid, name)


def test_lock_has_hashes_for_every_requirement_and_keeps_the_former_pins():
    text = LOCK.read_text(encoding="utf-8")
    hashed = r"((?:    --hash=sha256:[0-9a-f]{64}(?: \\)?\n)+)"
    blocks = re.findall(r"^([A-Za-z0-9_.-]+)==(\S+) \\\n" + hashed, text, re.M)
    pinned = {name.lower(): version for name, version, _ in blocks}
    requirement_lines = [ln for ln in text.splitlines() if re.match(r"^[A-Za-z0-9_.-]+==", ln)]
    assert len(blocks) == len(requirement_lines) >= 40
    for name, version in FORMER_PINS.items():
        assert pinned[name] == version, name
        assert f"{name} {version}" in text.split("# This file was autogenerated")[0], name
    direct = dict(ln.split("==") for ln in REQUIREMENTS.read_text(encoding="utf-8").splitlines()
                  if ln and not ln.startswith("#"))
    assert direct == FORMER_PINS
    assert "--python-platform x86_64-manylinux_2_28" in text and "--only-binary :all:" in text


